// Visual tour: drives the real UI and saves screenshots (used while developing; not an assertion test).
import { createRequire } from 'node:module';
import path from 'node:path';
import fs from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
const require = createRequire('/opt/node-tools/');
const { chromium } = require('playwright');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const outDir = process.argv[2] || '/tmp/tour'; fs.mkdirSync(outDir, { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1600, height: 960 } });
const errors = [];
page.on('console', m => { if (m.type() === 'error') errors.push(`[console] ${m.text()}`); });
page.on('pageerror', e => errors.push(`[pageerror] ${e.message}\n${e.stack?.split('\n').slice(0, 5).join('\n')}`));
await page.goto(pathToFileURL(path.join(root, 'CadForge.html')).href);
await page.waitForTimeout(300);
const shot = async n => { await page.waitForTimeout(200); await page.screenshot({ path: path.join(outDir, n + '.png') }); };
await shot('01-empty');
await page.evaluate(() => window.cadforge.ui.files.openSample());
await page.waitForTimeout(300);
await shot('02-sample');
// click an entity then show properties
await page.evaluate(() => { const { ui } = window.cadforge; ui.togglePalette('properties', true); });
await shot('03-props-none');
await page.evaluate(() => { const { app } = window.cadforge; const ed = app.active; ed.sel.add(ed.doc.entities[0].id); app.emit('change'); });
await shot('04-props-pline');
await page.evaluate(() => window.cadforge.ui.togglePalette('layers', true));
await shot('05-layers');
await page.evaluate(() => { window.cadforge.ui.togglePalette('layers', false); window.cadforge.ui.dialog('dsettings'); });
await shot('06-dsettings');
await page.keyboard.press('Escape');
await page.evaluate(() => { window.cadforge.ui.dialog('color', { value: 1, allowByLayer: true }); });
await shot('07-color');
await page.keyboard.press('Escape');
await page.click('.app-btn'); await shot('08-appmenu');
await page.keyboard.press('Escape');
console.log(errors.length ? errors.join('\n') : 'no console errors');
await browser.close();
